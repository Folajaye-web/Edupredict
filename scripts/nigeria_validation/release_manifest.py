"""Shared technical release-manifest reader for Phase 9 candidate monitoring.

Phase 9 uses the hashes generated by Phase 7C for the current candidate build.
Phase 10B/10C deliberately retain a separate fixed approval allowlist so a new
candidate is not silently promoted to a school pilot.
"""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[2]
MANIFEST_PATH = ROOT / "reports" / "nigeria_validation" / "phase7C_release_manifest.json"
EXPECTED_FEATURE_PIPELINE = "2.0-period-safe-school-aware"


def load_expected_hashes():
    if not MANIFEST_PATH.is_file():
        raise RuntimeError(f"Phase 7C technical release manifest missing: {MANIFEST_PATH}")
    try:
        manifest = json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise RuntimeError(f"Cannot read Phase 7C manifest: {exc}") from exc
    if manifest.get("status") != "TECHNICAL_RELEASE_READY":
        raise RuntimeError(f"Phase 7C technical gate is not ready: {manifest.get('status')!r}")
    if manifest.get("feature_pipeline_version") != EXPECTED_FEATURE_PIPELINE:
        raise RuntimeError("Phase 7C manifest does not identify the corrected feature pipeline.")
    if manifest.get("pilot_authorised", False):
        raise RuntimeError("Phase 7C must not grant school-pilot authorisation.")
    cls_hash = manifest.get("classification_sha256")
    reg_hash = manifest.get("regression_sha256")
    if not cls_hash or not reg_hash:
        raise RuntimeError("Phase 7C manifest is missing model hashes.")
    return {"classification": cls_hash, "regression": reg_hash}
